import {bundle} from '@remotion/bundler';
import {renderStill, selectComposition} from '@remotion/renderer';
import path from 'path';
import fs from 'fs';
const frames = process.argv.slice(2).map(Number);
const dir = fs.readdirSync('/opt/pw-browsers').filter(d=>d.startsWith('chromium_headless_shell'))[0];
const base = `/opt/pw-browsers/${dir}`;
const CH = fs.readdirSync(base).map(d=>`${base}/${d}/chrome-headless-shell`).find(p=>fs.existsSync(p));
const serveUrl = await bundle({entryPoint: path.resolve('src/index.ts')});
const comp = await selectComposition({serveUrl, id: 'Ad', browserExecutable: CH});
for (const frame of frames) await renderStill({composition: comp, serveUrl, frame, output: `work/st/f${String(frame).padStart(4,'0')}.png`, browserExecutable: CH, scale: 0.5});
console.log('done', CH);
